CREATE TABLE IF NOT EXISTS public.store_collections (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  site_id uuid NOT NULL REFERENCES public.sites(id) ON DELETE CASCADE,
  name text NOT NULL,
  slug text NOT NULL,
  description text,
  image text,
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (site_id, slug)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.store_collections TO authenticated;
GRANT SELECT ON public.store_collections TO anon;
GRANT ALL ON public.store_collections TO service_role;
ALTER TABLE public.store_collections ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "collections public read" ON public.store_collections;
CREATE POLICY "collections public read" ON public.store_collections FOR SELECT
  USING (is_active = true OR EXISTS (SELECT 1 FROM public.sites s WHERE s.id = site_id AND s.user_id = auth.uid()) OR public.has_role(auth.uid(), 'admin'));
DROP POLICY IF EXISTS "collections owner write" ON public.store_collections;
CREATE POLICY "collections owner write" ON public.store_collections FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM public.sites s WHERE s.id = site_id AND s.user_id = auth.uid()) OR public.has_role(auth.uid(), 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.sites s WHERE s.id = site_id AND s.user_id = auth.uid()) OR public.has_role(auth.uid(), 'admin'));

CREATE TABLE IF NOT EXISTS public.store_coupons (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  site_id uuid NOT NULL REFERENCES public.sites(id) ON DELETE CASCADE,
  code text NOT NULL,
  kind text NOT NULL DEFAULT 'percent',
  value numeric NOT NULL DEFAULT 0,
  min_order_inr numeric NOT NULL DEFAULT 0,
  usage_limit integer,
  used_count integer NOT NULL DEFAULT 0,
  expires_at timestamptz,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (site_id, code)
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.store_coupons TO authenticated;
GRANT ALL ON public.store_coupons TO service_role;
ALTER TABLE public.store_coupons ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "coupons owner manage" ON public.store_coupons;
