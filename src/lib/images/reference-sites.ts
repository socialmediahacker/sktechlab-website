export function normaliseCategoryName(value: string): string {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

/** Resolve a database category to the closest reference group from the PDF. */
export function referenceSitesForCategory(name: string, slug = ""): string[] {
  const target = normaliseCategoryName(`${name} ${slug}`);
  const targetTokens = new Set(target.split(" ").filter((token) => token.length > 2));
  let best: { score: number; sites: string[] } | null = null;

  for (const group of INDIA_REFERENCE_SITES) {
    const key = normaliseCategoryName(group.category);
    const phrases = [key, ...(CATEGORY_ALIASES[key] ?? [])].map(normaliseCategoryName);
    let score = phrases.some((phrase) => target.includes(phrase) || phrase.includes(target)) ? 100 : 0;
    for (const phrase of phrases) {
      const tokens = new Set(phrase.split(" ").filter((token) => token.length > 2));
      const common = [...tokens].filter((token) => targetTokens.has(token)).length;
      score = Math.max(score, common * 10 - Math.abs(tokens.size - targetTokens.size));
    }
    if (!best || score > best.score) best = { score, sites: group.sites };
  }

  return best && best.score >= 9 ? best.sites : [];
}
